import { ServerProperties } from './types';

export class ServerPropertiesHandler {
  private static readonly DEFAULT_PROPERTIES: ServerProperties = {
    'server-port': 25565,
    'server-ip': '0.0.0.0',
    motd: 'A MinecraftCloud Server',
    'max-players': 20,
    difficulty: 'normal',
    gamemode: 'survival',
    'online-mode': true,
    pvp: true,
    'allow-flight': false,
    'white-list': false,
    'view-distance': 10,
    'simulation-distance': 8,
    'spawn-protection': 16,
    'enable-rcon': true,
    'rcon.port': 25575,
    'rcon.password': 'mc-cloud-secure-rcon',
    'level-name': 'world',
    'enable-command-block': true,
    'allow-nether': true,
    'generate-structures': true,
    'max-tick-time': 60000,
    'network-compression-threshold': 256,
    'enforce-whitelist': false,
    'sync-chunk-writes': true,
  };

  /**
   * Parse a raw server.properties string into an object.
   */
  public static parse(content: string): ServerProperties {
    const properties: ServerProperties = { ...this.DEFAULT_PROPERTIES };
    const lines = content.split(/\r?\n/);

    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line || line.startsWith('#') || line.startsWith('!')) {
        continue;
      }

      const eqIndex = line.indexOf('=');
      if (eqIndex === -1) continue;

      const key = line.substring(0, eqIndex).trim();
      const value = line.substring(eqIndex + 1).trim();

      if (value === 'true') {
        properties[key] = true;
      } else if (value === 'false') {
        properties[key] = false;
      } else if (/^-?\d+$/.test(value)) {
        properties[key] = parseInt(value, 10);
      } else {
        // Unescape unicode if any (e.g., \u00A7)
        properties[key] = value.replace(/\\u([0-9a-fA-F]{4})/g, (_, code) =>
          String.fromCharCode(parseInt(code, 16))
        );
      }
    }

    return properties;
  }

  /**
   * Serialize an object into standard server.properties format.
   */
  public static stringify(properties: ServerProperties): string {
    const timestamp = new Date().toISOString();
    const lines: string[] = [
      '# Minecraft server properties generated by MinecraftCloud Platform',
      `# Generated at ${timestamp}`,
      '',
    ];

    const merged = { ...this.DEFAULT_PROPERTIES, ...properties };

    // Group common properties first for readability
    const priorityKeys = [
      'motd',
      'server-port',
      'server-ip',
      'max-players',
      'difficulty',
      'gamemode',
      'online-mode',
      'pvp',
      'allow-flight',
      'white-list',
      'view-distance',
      'simulation-distance',
      'spawn-protection',
      'enable-rcon',
      'rcon.port',
      'rcon.password',
      'level-name',
      'level-seed',
    ];

    const processedKeys = new Set<string>();

    for (const key of priorityKeys) {
      if (key in merged && merged[key] !== undefined) {
        lines.push(`${key}=${merged[key]}`);
        processedKeys.add(key);
      }
    }

    lines.push('');
    lines.push('# Additional Engine Settings');

    for (const [key, val] of Object.entries(merged)) {
      if (!processedKeys.has(key) && val !== undefined) {
        lines.push(`${key}=${val}`);
      }
    }

    return lines.join('\n') + '\n';
  }
}
